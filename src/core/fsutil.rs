//! Filesystem helpers.

use std::path::Path;

use walkdir::WalkDir;

/// Regular-file bytes under `path`; 0 if missing.
pub fn dir_size(path: &Path) -> u64 {
    WalkDir::new(path)
        .into_iter()
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().is_file())
        .filter_map(|e| e.metadata().ok())
        .map(|m| m.len())
        .sum()
}
